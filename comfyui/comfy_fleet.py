def load_all_machines(config: dict) -> dict:
    reports_dir = Path(config["reports_dir"])
    data = {}

    for hostname, machine_cfg in config["machines"].items():
        print(f"Loading {hostname}...")
        files = load_machine_files(reports_dir, hostname)
        if not files:
            print(f"  SKIP: no files found for {hostname}")
            continue

        newest_mtime = max((f.stat().st_mtime for f in files.values()), default=None)
        scan_age_days = (
            round((datetime.now().timestamp() - newest_mtime) / 86400, 1)
            if newest_mtime is not None else None
        )
        if scan_age_days is not None and scan_age_days > STALE_DAYS:
            print(f"  WARNING: {hostname} scan is {scan_age_days:.1f} days old (stale threshold: {STALE_DAYS})")

        entry = {
            "config":   machine_cfg,
            "files":    files,
            "models":   {},   # filename.lower() -> row
            "nodes":    set(),
            "nodes_disabled": set(),
            "full_map": [],
            "scan_age_days": scan_age_days,
        }

        if "models" in files:
            rows = load_csv(files["models"])
            for r in rows:
                entry["models"][r["filename"].lower()] = r
            print(f"  {len(entry['models'])} models")

        if "nodes" in files:
            entry["nodes"], entry["nodes_disabled"] = load_nodes(files["nodes"])
            n_disabled = len(entry["nodes_disabled"])
            suffix = f" ({n_disabled} disabled)" if n_disabled else ""
            print(f"  {len(entry['nodes'])} custom nodes{suffix}")

        if "full_map" in files:
            entry["full_map"] = load_csv(files["full_map"])
            print(f"  {len(entry['full_map'])} full_map rows")

        if "unused" in files:
            entry["unused"] = load_csv(files["unused"])

        if "missing" in files:
            entry["missing_csv"] = load_csv(files["missing"])

        data[hostname] = entry

    return data


