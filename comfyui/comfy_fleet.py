def find_latest(reports_dir: Path, hostname: str, pattern: str) -> Path | None:
    """Find the most recent file matching hostname + pattern glob."""
    matches = sorted(reports_dir.glob(f"{hostname}-{pattern}"))
    return matches[-1] if matches else None


def load_machine_files(reports_dir: Path, hostname: str) -> dict:
    """Load all report files for a machine, returning the latest of each type."""
    files = {}
    patterns = {
        "models":   "Models-*.csv",
        "full_map": "WorkflowMap-*-full_map.csv",
        "usage":    "WorkflowMap-*-model_usage.csv",
        "unused":   "WorkflowMap-*-unused_models.csv",
        "missing":  "WorkflowMap-*-missing_models.csv",
        "nodes":    "CustomNodes-*.txt",
    }
    for key, pattern in patterns.items():
        f = find_latest(reports_dir, hostname, pattern)
        if f:
            files[key] = f
        else:
            print(f"  WARNING: No {key} file found for {hostname}")
    return files


def load_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


DISABLED_SUFFIX = ".disabled"

def load_nodes(path: Path) -> tuple[set[str], set[str]]:
    """Returns (all_node_names, disabled_node_names), both lowercased.

    ComfyUI Manager disables a node by renaming its folder to
    '<name>.disabled' -- left unhandled, that shows up in the fleet matrix
    as a distinct, permanently-"missing" node instead of the same node in a
    disabled state. Strip the suffix and track disabled status separately
    instead.
    """
    nodes    = set()
    disabled = set()
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line and line[0].isdigit():
                name = line.split(". ", 1)[-1].strip().lower()
                if name == "__pycache__":
                    continue
                if name.endswith(DISABLED_SUFFIX):
                    name = name[:-len(DISABLED_SUFFIX)]
                    if not name:
                        continue
                    disabled.add(name)
                nodes.add(name)
    return nodes, disabled


