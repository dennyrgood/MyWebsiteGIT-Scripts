# Subdir mismatch analysis
# Find models that exist in both source and dest but at different relative paths
# ---------------------------------------------------------------------------

def analyze_subdir_mismatches(data: dict, config: dict) -> list:
    """Find models on both source and dest but in different subdirectories."""
    source_host = next(
        (h for h, m in config["machines"].items() if m.get("is_source")), None
    )
    if not source_host or source_host not in data:
        return []

    src_models = data[source_host]["models"]

    # Build lookup: filename.lower() -> normalized relative path (forward slashes)
    def norm(p):
        return p.replace("\\\\", "/").replace("\\", "/")

    src_relpath = {}
    for fn_lower, row in src_models.items():
        rel = row.get("relative_path", "")
        if rel:
            src_relpath[fn_lower] = norm(rel)

    mismatches = []
    seen = set()

    for hostname, machine in data.items():
        if hostname == source_host:
            continue
        if not config["machines"][hostname].get("models_bare"):
            continue

        for fn_lower, row in machine["models"].items():
            if fn_lower not in src_relpath:
                continue

            dest_rel_raw = row.get("relative_path", "")
            dest_rel = norm(dest_rel_raw)
            src_rel  = src_relpath[fn_lower]

            src_subdir  = "/".join(src_rel.split("/")[:-1])
            dest_subdir = "/".join(dest_rel.split("/")[:-1])

            if src_subdir.lower() != dest_subdir.lower():
                key = (fn_lower, src_rel.lower())
                if key not in seen:
                    seen.add(key)
                    mismatches.append({
                        "filename":    row["filename"],
                        "src_rel":     src_rel,
                        "dest_rel":    dest_rel,
                        "src_subdir":  src_subdir,
                        "dest_subdir": dest_subdir,
                        "hostname":    hostname,
                        "size_gb":     float(row.get("size_gb", 0)),
                    })

    return sorted(mismatches, key=lambda x: x["filename"].lower())


def generate_subdir_fix_bat(mismatches: list, src_root: str, dest_root: str) -> str:
    """Generate robocopy bat to move files to correct subdirs on Models_bare."""
    from collections import defaultdict
    lines = [
        "@echo off",
        "REM ============================================================",
        "REM  fix_subdir_structure.bat",
        "REM  Copies models in Models_bare to match ImageBeast subdir structure",
        "REM  Run this on IMAGEBEAST (or any machine with access to Models_bare)",
        f"REM  {len(mismatches)} files to relocate",
        "REM  SAFE: copies to new location only - delete old copies manually after verifying",
        "REM ============================================================",
        "",
        f"set DST={dest_root}",
        "",
    ]

    by_dest = defaultdict(list)
    for m in mismatches:
        by_dest[m["src_subdir"]].append(m)

    for dest_subdir, items in sorted(by_dest.items()):
        label = dest_subdir if dest_subdir else "(root)"
        lines.append(f"REM === Move to: {label} ===")
        for m in items:
            cur_win  = m["dest_subdir"].replace("/", "\\")
            tgt_win  = dest_subdir.replace("/", "\\")
            cur_dir  = f'%DST%\\{cur_win}' if cur_win else "%DST%"
            tgt_dir  = f'%DST%\\{tgt_win}' if tgt_win else "%DST%"
            lines.append(f'REM  {m["filename"]}  ({m["size_gb"]:.2f} GB)')
            lines.append(f'REM  FROM: {cur_dir}')
            lines.append(f'REM  TO  : {tgt_dir}')
            lines.append(f'robocopy "{cur_dir}" "{tgt_dir}" "{m["filename"]}" /COPY:DAT /R:2 /W:5')
            lines.append("")

    lines += [
        "echo.",
        "echo ============================================================",
        "echo  COPY COMPLETE",
        "echo  Verify files are in correct locations then delete old copies",
        "echo  Old files were NOT auto-deleted for safety",
        "echo ============================================================",
        "pause",
    ]
    return "\n".join(lines)



# ---------------------------------------------------------------------------
# Output rotation
# fleet-output/ and history/ grow one file-set per run forever. This lists
# what's beyond the retention window; it never deletes unless the caller
# passes --confirm-prune, so a plain run is always non-destructive.
# ---------------------------------------------------------------------------

def find_prune_candidates(output_dir: Path, history_dir: Path, reports_dir: Path, keep: int) -> dict:
    """Return {'output': [...], 'history': [...], 'inputs': [...]} beyond the newest `keep` runs."""
    run_ts = sorted({
        m.group(1)
        for f in output_dir.glob("*_*.html")
        if (m := re.search(r"(\d{4}-\d{2}-\d{2}_\d{4})", f.name))
    } | {
        m.group(1)
        for f in output_dir.glob("summary_*.txt")
        if (m := re.search(r"(\d{4}-\d{2}-\d{2}_\d{4})", f.name))
    })
    stale_ts = set(run_ts[:-keep]) if len(run_ts) > keep else set()

    output_candidates = [
        f for f in output_dir.iterdir()
        if f.is_file() and any(ts in f.name for ts in stale_ts)
    ]

    snapshots = sorted(history_dir.glob("snapshot-*.json"))
    history_candidates = snapshots[:-keep] if len(snapshots) > keep else []

    # Raw scan inputs are per-machine, timestamped independently by each
    # machine's own scan run -- keep the newest `keep` timestamps per machine,
    # not globally, since machines don't scan in lockstep.
    input_candidates = []
    by_machine_ts = defaultdict(set)
    for f in reports_dir.iterdir():
        if not f.is_file():
            continue
        m = re.match(r"^(IMAGEBEAST|CHATWORKHORSE|TRAVELBEAST)-.*?(\d{4}-\d{2}-\d{2}_\d{4})", f.name)
        if m:
            by_machine_ts[m.group(1)].add(m.group(2))

    stale_input_ts = {}
    for machine, ts_set in by_machine_ts.items():
        ts_sorted = sorted(ts_set)
        stale_input_ts[machine] = set(ts_sorted[:-keep]) if len(ts_sorted) > keep else set()

    for f in reports_dir.iterdir():
        if not f.is_file():
            continue
        m = re.match(r"^(IMAGEBEAST|CHATWORKHORSE|TRAVELBEAST)-.*?(\d{4}-\d{2}-\d{2}_\d{4})", f.name)
        if m and m.group(2) in stale_input_ts.get(m.group(1), set()):
            input_candidates.append(f)

    return {
        "output":   sorted(output_candidates),
        "history":  history_candidates,
        "inputs":   sorted(input_candidates),
    }


def prune_outputs(output_dir: Path, history_dir: Path, reports_dir: Path, keep: int, confirm: bool):
    candidates = find_prune_candidates(output_dir, history_dir, reports_dir, keep)
    total = len(candidates["output"]) + len(candidates["history"]) + len(candidates["inputs"])
    if total == 0:
        print(f"Prune: nothing beyond the last {keep} runs — nothing to do.")
        return

    print(f"\nPrune candidates (older than the last {keep} runs):")
    for f in candidates["inputs"]:
        print(f"  {f.name}")
    for f in candidates["output"]:
        print(f"  fleet-output/{f.name}")
    for f in candidates["history"]:
        print(f"  history/{f.name}")
    print(f"Total: {total} files")

    if not confirm:
        print("Dry run only — re-run with --prune-output --confirm-prune to actually delete these.")
        return

    for f in candidates["inputs"] + candidates["output"] + candidates["history"]:
        f.unlink()
    print(f"Deleted {total} files.")


